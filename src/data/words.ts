/**
 * Core N5 vocabulary.
 *
 * Hand-authored rather than imported. The obvious sources (JMdict and friends)
 * are CC-BY-SA, and share-alike data sitting inside an MIT repository is a
 * licensing tangle that is painful to unpick once it is in the history. The
 * cost of writing it out is that mistakes are mine, so the tests hold this file
 * to the same standard as the counters: every reading must be kana, must be
 * typeable through the app's own romaji converter, and no two entries may
 * collide.
 *
 * Words written in kana in ordinary use are stored that way — これ, とても,
 * たくさん — which is most of what the kanji deck could never reach. Where a
 * word is normally written with kanji, `word` carries the kanji and `reading`
 * the kana.
 */

export type WordKind = 'noun' | 'verb' | 'adjective' | 'adverb' | 'expression' | 'pronoun';

export interface WordEntry {
  /** as normally written, e.g. 食べる or これ */
  word: string;
  /** kana reading; equal to `word` for kana-only vocabulary */
  reading: string;
  /** accepted English meanings; the first is the canonical one */
  meanings: string[];
  kind: WordKind;
  groupId: string;
}

export interface WordGroup {
  id: string;
  label: string;
  blurb: string;
  words: WordEntry[];
}

