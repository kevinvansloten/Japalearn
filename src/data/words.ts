export const WORD_GROUPS: WordGroup[] = SPECS.map((spec) => ({
  id: spec.id,
  label: spec.label,
  blurb: spec.blurb,
  words: spec.rows.map(([word, reading, meanings, kind]) => ({
    word,
    reading,
    meanings,
    kind,
    groupId: spec.id,
  })),
}));

export const ALL_WORDS: WordEntry[] = WORD_GROUPS.flatMap((g) => g.words);

/** Kana-only entries have no reading to ask for. */
export const hasKanji = (entry: WordEntry): boolean => entry.word !== entry.reading;
